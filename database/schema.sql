CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  avatar_mime VARCHAR(32),
  avatar_data BYTEA,
  avatar_updated_at TIMESTAMPTZ,
  role VARCHAR(16) NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_users_created ON users (created_at);
CREATE INDEX IF NOT EXISTS idx_users_role_active ON users (role, is_active);

CREATE TABLE IF NOT EXISTS tasks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  description TEXT,
  start_date DATE,
  due_date DATE,
  status VARCHAR(16) NOT NULL DEFAULT 'To do' CHECK (status IN ('To do', 'In Progress', 'Done')),
  priority VARCHAR(16) NOT NULL DEFAULT 'Medium' CHECK (priority IN ('Low', 'Medium', 'High')),
  assignee VARCHAR(120),
  owner_id INTEGER REFERENCES users (id) ON DELETE CASCADE,
  completed_at TIMESTAMPTZ,
  seed_key VARCHAR(100) UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_tasks_owner_updated ON tasks (owner_id, updated_at);
CREATE INDEX IF NOT EXISTS idx_tasks_owner_due ON tasks (owner_id, due_date);
CREATE INDEX IF NOT EXISTS idx_tasks_owner_completed ON tasks (owner_id, completed_at);

CREATE TABLE IF NOT EXISTS auth_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_auth_sessions_expires_at ON auth_sessions (expires_at);

CREATE TABLE IF NOT EXISTS admin_activity (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  target_user_id INTEGER REFERENCES users (id) ON DELETE CASCADE,
  target_type VARCHAR(40) NOT NULL DEFAULT 'user',
  target_id INTEGER,
  action VARCHAR(40) NOT NULL,
  description VARCHAR(255) NOT NULL DEFAULT '',
  details JSONB,
  seed_key VARCHAR(120) UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_admin_activity_created ON admin_activity (created_at);
CREATE INDEX IF NOT EXISTS idx_admin_activity_actor ON admin_activity (actor_id, created_at);
CREATE INDEX IF NOT EXISTS idx_admin_activity_action_created ON admin_activity (action, created_at);

CREATE TABLE IF NOT EXISTS admin_guard (
  id SMALLINT PRIMARY KEY CHECK (id = 1)
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER REFERENCES users (id) ON DELETE SET NULL,
  email_hash CHAR(64) NOT NULL,
  request_ip_hash CHAR(64) NOT NULL,
  token_hash CHAR(64) UNIQUE,
  requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMPTZ,
  used_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_password_reset_email_requested ON password_reset_tokens (email_hash, requested_at);
CREATE INDEX IF NOT EXISTS idx_password_reset_ip_requested ON password_reset_tokens (request_ip_hash, requested_at);

CREATE OR REPLACE FUNCTION update_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS users_updated_at ON users;
CREATE TRIGGER users_updated_at
BEFORE UPDATE ON users
FOR EACH ROW EXECUTE FUNCTION update_updated_at();

DROP TRIGGER IF EXISTS tasks_updated_at ON tasks;
CREATE TRIGGER tasks_updated_at
BEFORE UPDATE ON tasks
FOR EACH ROW EXECUTE FUNCTION update_updated_at();
